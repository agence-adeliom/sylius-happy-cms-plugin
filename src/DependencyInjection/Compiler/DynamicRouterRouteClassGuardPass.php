<?php

declare(strict_types=1);

namespace Adeliom\SyliusHappyCMSPlugin\DependencyInjection\Compiler;

use Adeliom\SyliusHappyCMSPlugin\Entity\Cmf\Route as BaseRoute;
use Symfony\Component\DependencyInjection\Compiler\CompilerPassInterface;
use Symfony\Component\DependencyInjection\ContainerBuilder;
use Symfony\Component\DependencyInjection\Exception\InvalidArgumentException;
use Symfony\Component\DependencyInjection\Reference;

/**
 * Checks the route class of the CMF dynamic router, given by `sylius_happy_cms.route.route_model`.
 *
 * - No `route_model` yet (before `make:happy-cms:install`): the route class is the base `Route` mapped superclass
 *   of the plugin, which has no table. The dynamic router is left out of the chain router, so unknown URLs answer
 *   404 from the other routers instead of a Doctrine `MappingException` (500).
 * - A route class that does not exist (for example set through the `cmf_routing.dynamic.persistence.orm.route_class`
 *   parameter): the container build fails, as it does for a wrong `route_model`.
 */
final class DynamicRouterRouteClassGuardPass implements CompilerPassInterface
{
    public const CHAIN_ROUTER = 'cmf_routing.router';

    public const DYNAMIC_ROUTER = 'cmf_routing.dynamic_router';

    public const ROUTE_CLASS_PARAMETER = 'cmf_routing.dynamic.persistence.orm.route_class';

    public function process(ContainerBuilder $container): void
    {
        if (!$container->hasDefinition(self::CHAIN_ROUTER) || !$container->hasParameter(self::ROUTE_CLASS_PARAMETER)) {
            return;
        }

        $routeClass = $container->getParameterBag()->resolveValue($container->getParameter(self::ROUTE_CLASS_PARAMETER));

        if (BaseRoute::class === $routeClass) {
            $this->removeTheDynamicRouter($container);

            return;
        }

        if (!is_string($routeClass) || !class_exists($routeClass)) {
            throw new InvalidArgumentException(sprintf(
                'The CMF route class "%s" (parameter "%s") does not exist. Set "sylius_happy_cms.route.route_model" to your route entity (generated by "make:happy-cms:install").',
                is_string($routeClass) ? $routeClass : get_debug_type($routeClass),
                self::ROUTE_CLASS_PARAMETER,
            ));
        }
    }

    private function removeTheDynamicRouter(ContainerBuilder $container): void
    {
        $chainRouter = $container->getDefinition(self::CHAIN_ROUTER);
        $calls = array_values(array_filter(
            $chainRouter->getMethodCalls(),
            fn (mixed $call): bool => !$this->addsTheDynamicRouter($call),
        ));

        if (count($calls) === count($chainRouter->getMethodCalls())) {
            return;
        }

        $chainRouter->setMethodCalls($calls);

        $container->log($this, sprintf(
            'The "%s" router has been removed from "%s": "sylius_happy_cms.route.route_model" is not configured. Run "make:happy-cms:install" to serve CMS routes.',
            self::DYNAMIC_ROUTER,
            self::CHAIN_ROUTER,
        ));
    }

    private function addsTheDynamicRouter(mixed $call): bool
    {
        if (!is_array($call) || 'add' !== ($call[0] ?? null) || !is_array($call[1] ?? null)) {
            return false;
        }

        $router = $call[1][0] ?? null;

        return $router instanceof Reference && self::DYNAMIC_ROUTER === (string) $router;
    }
}
